let currentLang = localStorage.getItem("bmb-language") || "en";

const languageToggle = document.getElementById("languageToggle");

function setLanguage(lang) {

currentLang = lang;

document.documentElement.lang = lang;

document.body.classList.toggle("bn", lang === "bn");

document.querySelectorAll("[data-i18n]").forEach(el => {

const key = el.dataset.i18n;

if (translations[lang][key] !== undefined) {
el.innerHTML = translations[lang][key];
}

});

languageToggle.textContent = lang === "en" ? "বাংলা" : "English";

localStorage.setItem("bmb-language", lang);

}

languageToggle.addEventListener("click", () => {

setLanguage(currentLang === "en" ? "bn" : "en");

});

document.getElementById("menuToggle").addEventListener("click", () => {

document.getElementById("mainNav").classList.toggle("open");

});

document.querySelectorAll(".main-nav a").forEach(a => {

a.addEventListener("click", () => {
document.getElementById("mainNav").classList.remove("open");
});

});

document.getElementById("year").textContent = new Date().getFullYear();

document.getElementById("locateMe").addEventListener("click", () => {

const output = document.getElementById("locationResult");

if (!navigator.geolocation) {

output.textContent = currentLang === "bn"
? "এই ব্রাউজারে GPS সুবিধা নেই।"
: "Geolocation is not supported by this browser.";

return;

}

output.textContent = currentLang === "bn"
? "আপনার অবস্থানের অনুমতি চাওয়া হচ্ছে…"
: "Requesting location permission…";

navigator.geolocation.getCurrentPosition(

pos => {

const lat = pos.coords.latitude.toFixed(5);
const lon = pos.coords.longitude.toFixed(5);

output.textContent = currentLang === "bn"
? `আপনার অবস্থান: ${lat}, ${lon}`
: `Your coordinates: ${lat}, ${lon}`;

},

() => {

output.textContent = currentLang === "bn"
? "অবস্থান পাওয়া যায়নি। ব্রাউজারের Location Permission চালু করুন।"
: "Location unavailable. Please allow location access in your browser.";

},

{
enableHighAccuracy: true,
timeout: 10000
}

);

});

setLanguage(currentLang);
